import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createSavedViewsStore } from '../saved-views.js';
import { browserFixture } from './browser-fixture.mjs';

test('mobile preset editor validates scope, retries current edits and restores deletions', async t => {
  const dir = await mkdtemp(join(tmpdir(), 'preset-editor-'));
  t.after(() => rm(dir, { recursive: true, force: true }));
  const savedViews = createSavedViewsStore(join(dir, 'views.json'));
  const list = Object.assign(async () => ({}), { viewer: async () => 'demo' });
  const { page, origin, errors } = await browserFixture(t, { list, savedViews });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(origin + '/settings.html');
  await page.getByRole('button', { name: 'Create your first preset' }).click();
  const submit = page.locator('.preset-form button[type=submit]');
  const field = key => page.locator('#pf-' + key);
  const msg = key => page.locator('#msg-' + key).innerText();
  await submit.click();
  assert.equal(await msg('label'), 'Enter a label.');
  assert.equal(await msg('body'), 'Enter the comment text to insert.');
  await field('label').fill('Build image'); await field('body').fill('[build]');
  await page.getByLabel('Only these repositories or organizations').check();
  await submit.click(); assert.match(await msg('scope'), /Add a repository or an org/);
  await field('repos').fill('invalid'); await field('repos').press('Enter');
  assert.match(await msg('repos'), /Use owner\/name/);
  await field('repos').fill('maple/api'); await field('repos').press('Enter');
  await field('repos').fill('Maple/API'); await field('repos').press('Enter');
  assert.match(await msg('repos'), /already added/); await field('repos').fill('');
  await field('orgs').fill('bad_name'); await field('orgs').press('Enter');
  assert.match(await msg('orgs'), /Use an org or user name/);
  await field('orgs').fill('maple/api'); await field('orgs').press('Enter');
  assert.match(await msg('orgs'), /Enter just the org or user/);
  await field('orgs').fill('orbit'); await field('orgs').press('Enter');
  assert.equal(await field('scope').innerText(), 'Shows on PRs in maple/api, or in any repo owned by orbit.');
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.route('**/api/quick-comments', route => route.fulfill({ status: 503, json: { error: 'Try again' } }), { times: 1 });
  await submit.click(); await page.getByText('Retry', { exact:true }).waitFor();
  await field('body').fill('[build-new]'); await page.getByText('Retry', {exact:true}).click();
  const row = page.locator('.preset-item'); await row.waitFor();
  assert.equal(await row.locator('code').innerText(), '[build-new]');
  await page.locator('#new-preset').click(); await field('label').fill('BUILD IMAGE'); await submit.click();
  assert.match(await msg('label'), /already exists/); await page.keyboard.press('Escape');
  await row.getByText('Edit', {exact:true}).click(); await field('body').fill('updated'); await submit.click();
  await row.getByText('Delete', {exact:true}).click(); await page.keyboard.press('Escape');
  await row.getByText('Delete', {exact:true}).click(); await page.getByText('Delete preset', {exact:true}).click();
  await page.getByText('Undo', {exact:true}).click(); await row.waitFor(); await page.reload();
  assert.equal(await row.locator('code').innerText(), 'updated'); assert.deepEqual(errors, []);
});
