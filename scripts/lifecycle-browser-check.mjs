import test from 'node:test';
import assert from 'node:assert/strict';
import { browserFixture } from './browser-fixture.mjs';
import { lifecycleFixture } from './lifecycle-fixture.mjs';
import { ApiError } from '../github.js';
test('lifecycle menu confirms close, preserves errors, updates children and reopens', async t => {
  const list = lifecycleFixture(), close = list.closePull; let fail = true;
  list.closePull = async input => { if (fail) throw new ApiError('Close rejected', 403); return close(input); };
  const { page, origin, errors } = await browserFixture(t, { list });
  await page.goto(`${origin}/?q=involves%3A%40me`);
  const row = page.locator('.pr-row[data-pr-id="demo-1"]');
  await row.locator('.lifecycle-action').click();
  assert.equal(await page.locator('#pr-lifecycle hr').count(), 0);
  await page.getByRole('button', { name: 'Close pull request…', exact: true }).click();
  await page.getByRole('textbox', { name: 'Comment', exact: true }).fill('Testing locally');
  await page.screenshot({ path: '/tmp/close-pr-preview.png' });
  await page.getByRole('button', { name: 'Close pull request', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'Close rejected' }).waitFor();
  assert.equal(await page.getByRole('textbox', { name: 'Comment', exact: true }).inputValue(), 'Testing locally');
  fail = false;
  await page.getByRole('button', { name: 'Close pull request', exact: true }).click();
  await row.locator('.lifecycle-action.closed').waitFor();
  await page.locator('[data-pr-id="demo-2"] .dependency-chip').filter({ hasText: 'closed' }).waitFor();
  await row.locator('.lifecycle-action').click();
  await page.getByRole('button', { name: 'Reopen pull request', exact: true }).click();
  await row.locator('.lifecycle-action.open').waitFor();
  // Explicitly request open PRs; a bare launch now remembers the all-state query.
  await page.goto(`${origin}/?state=open`);
  await row.locator('.lifecycle-action').click();
  await page.getByRole('button', { name: 'Close pull request…', exact: true }).click();
  await page.getByRole('button', { name: 'Close pull request', exact: true }).click();
  await row.waitFor({ state: 'detached' });
  assert.deepEqual(errors, []);
});
